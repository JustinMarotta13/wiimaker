fn glyph_index(ch: u8) -> Option<usize> {
    if (FIRST_CHAR..=LAST_CHAR).contains(&ch) {
        Some((ch - FIRST_CHAR) as usize)
    } else {
        None
    }
}

/// Resolve a code unit to a printable glyph (unknown → `?`; space stays space).
pub fn map_char(ch: char) -> u8 {
    if ch == '\n' || ch == '\r' {
        return 0;
    }
    let b = if ch.is_ascii() {
        ch as u8
    } else {
        MISSING_CHAR
    };
    if glyph_index(b).is_some() {
        b
    } else {
        MISSING_CHAR
    }
}

pub fn glyph_bits(ch: u8) -> [u8; 8] {
    let idx = glyph_index(ch)
        .or_else(|| glyph_index(MISSING_CHAR))
        .unwrap_or(0);
    GLYPHS[idx]
}

/// UV rect (`x, y, w, h` in 0..1) for `ch` in the packed atlas.
pub fn glyph_uv(ch: u8) -> (f32, f32, f32, f32) {
    let mapped = if glyph_index(ch).is_some() {
        ch
    } else {
        MISSING_CHAR
    };
    let i = (mapped - FIRST_CHAR) as u32;
    let col = i % FONT_COLS;
    let row = i / FONT_COLS;
    let u = col as f32 * FONT_CELL_PX as f32 / FONT_ATLAS_W as f32;
    let v = row as f32 * FONT_CELL_PX as f32 / FONT_ATLAS_H as f32;
    let du = FONT_CELL_PX as f32 / FONT_ATLAS_W as f32;
    let dv = FONT_CELL_PX as f32 / FONT_ATLAS_H as f32;
    (u, v, du, dv)
}

/// White-on-transparent RGBA8 atlas (row-major).
pub fn atlas_rgba8() -> (u32, u32, Vec<u8>) {
    let mut rgba = vec![0u8; (FONT_ATLAS_W * FONT_ATLAS_H * 4) as usize];
    for (i, glyph) in GLYPHS.iter().enumerate() {
        let col = (i as u32) % FONT_COLS;
        let row = (i as u32) / FONT_COLS;
        let ox = col * FONT_CELL_PX;
        let oy = row * FONT_CELL_PX;
        for py in 0..FONT_CELL_PX {
            let bits = glyph[py as usize];
            for px in 0..FONT_CELL_PX {
                if (bits >> px) & 1 == 0 {
                    continue;
                }
                let x = ox + px;
                let y = oy + py;
                let idx = ((y * FONT_ATLAS_W + x) * 4) as usize;
                rgba[idx] = 255;
                rgba[idx + 1] = 255;
                rgba[idx + 2] = 255;
                rgba[idx + 3] = 255;
            }
        }
    }
    (FONT_ATLAS_W, FONT_ATLAS_H, rgba)
}

pub fn atlas_image() -> RgbaImage {
    let (w, h, rgba) = atlas_rgba8();
    ImageBuffer::from_raw(w, h, rgba).expect("hud font atlas size")
}

/// Write `fixtures/hud_font.png` (or `path`) from the same bits the host samples.
pub fn write_hud_font_png(path: impl AsRef<Path>) -> Result<()> {
    let img = atlas_image();
    img.save(path.as_ref())
        .with_context(|| format!("write {}", path.as_ref().display()))
}

/// C header for `runtime/wii` GX glyphs. Same bits as [`GLYPHS`] / host atlas.
pub fn font8x8_c_header() -> String {
    let mut s = String::new();
    s.push_str("/*\n");
    s.push_str(" * Generated from crates/wiimaker-assets/src/font.rs (font8x8 / public domain).\n");
    s.push_str(" * Do not invent a second font — regenerate from those bits.\n");
    s.push_str(" */\n");
    s.push_str("#ifndef WIIMAKER_FONT8X8_H\n");
    s.push_str("#define WIIMAKER_FONT8X8_H\n\n");
    s.push_str("#include <stdint.h>\n\n");
    s.push_str("#define FONT8X8_CELL 8\n");
    s.push_str("#define FONT8X8_FIRST 32\n");
    s.push_str("#define FONT8X8_LAST 126\n");
    s.push_str("#define FONT8X8_MISSING 63 /* '?' */\n");
    s.push_str("#define FONT8X8_COUNT 95\n\n");
    s.push_str("/* Row-major 8x8 bits; bit 0 is the leftmost pixel (font8x8 convention). */\n");
    s.push_str("static const uint8_t FONT8X8_GLYPHS[FONT8X8_COUNT][8] = {\n");
    for (i, glyph) in GLYPHS.iter().enumerate() {
        let ch = FIRST_CHAR + i as u8;
        let hex: Vec<String> = glyph.iter().map(|b| format!("0x{b:02X}")).collect();
        s.push_str(&format!(
            "    {{ {}, }}, /* {} */\n",
            hex.join(", "),
            glyph_c_comment(ch)
        ));
    }
    s.push_str("};\n\n");
    s.push_str("#endif /* WIIMAKER_FONT8X8_H */\n");
    s
}

fn glyph_c_comment(ch: u8) -> String {
    let shown = match ch {
        b'\\' => "\\\\".to_string(),
        b'\'' => "\\'".to_string(),
        _ => (ch as char).to_string(),
    };
    format!("{ch} '{shown}'")
}

/// Write `runtime/wii/include/font8x8.h` (or `path`) from [`GLYPHS`].
pub fn write_font8x8_header(path: impl AsRef<Path>) -> Result<()> {
    std::fs::write(path.as_ref(), font8x8_c_header())
        .with_context(|| format!("write {}", path.as_ref().display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn printable_set_covers_ascii() {
        assert_eq!(GLYPHS.len(), (LAST_CHAR - FIRST_CHAR + 1) as usize);
        assert_eq!(map_char('A'), b'A');
        assert_eq!(map_char('?'), b'?');
        assert_eq!(map_char('\u{2603}'), b'?');
    }

    #[test]
    fn space_is_empty_a_is_ink() {
        assert!(glyph_bits(b' ').iter().all(|b| *b == 0));
        assert!(glyph_bits(b'A').iter().any(|b| *b != 0));
    }

    #[test]
    fn atlas_has_ink_for_a() {
        let (w, h, rgba) = atlas_rgba8();
        assert_eq!((w, h), (128, 64));
        let (u, v, du, dv) = glyph_uv(b'A');
        let mut ink = 0u32;
        for py in 0..8 {
            for px in 0..8 {
                let su = u + du * ((px as f32 + 0.5) / 8.0);
                let sv = v + dv * ((py as f32 + 0.5) / 8.0);
                let x = ((su * w as f32) as u32).min(w - 1);
                let y = ((sv * h as f32) as u32).min(h - 1);
                let i = ((y * w + x) * 4) as usize;
                if rgba[i + 3] > 0 {
                    ink += 1;
                }
            }
        }
        assert!(ink > 8, "A should have ink, got {ink}");
    }

    #[test]
    fn fixture_png_matches_atlas() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("fixtures/hud_font.png");
        let file = image::open(&path).expect("hud_font.png").to_rgba8();
        let gen = atlas_image();
        assert_eq!(file.dimensions(), gen.dimensions());
        assert_eq!(file.as_raw(), gen.as_raw());
    }

    #[test]
    fn wii_c_header_matches_glyph_bits() {
        let path =
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../../runtime/wii/include/font8x8.h");
        let on_disk = std::fs::read_to_string(&path).expect("font8x8.h");
        assert_eq!(on_disk, font8x8_c_header());
        assert!(on_disk.contains("0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00"));
    }
}
